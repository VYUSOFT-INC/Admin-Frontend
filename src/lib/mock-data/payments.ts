import type { VendorType } from "@/lib/mock-data/vendors";

/**
 * Matches the Figma "payments payout" design's status TABS: All / Pending / Processed /
 * On Hold / Overdue. The table's STATUS column badge uses the same four values.
 */
export type PayoutStatus = "Pending" | "Processed" | "On Hold" | "Overdue";

/** Matches the Figma "payout detail" Transaction Breakdown table's FULFILLMENT column badge. */
export type PayoutFulfillment = "Delivery" | "Pickup" | "Walk-in";

/**
 * A single order row in the Payout Detail screen's "Transaction Breakdown" table. The Figma
 * design shows a fixed-size sample of the payout's orders (at most 8 rows) with a footer
 * "Subtotal (N Orders)" row that reflects the *full* `ordersCount`/`grossAmount`/`commission`/
 * `netAmount` already on the parent `Payout` — not a sum of just the visible sample rows — so
 * these line items exist purely to illustrate a representative cross-section of the payout.
 */
export interface PayoutOrderLine {
  /** e.g. "#ORD-20481". */
  orderId: string;
  fulfillment: PayoutFulfillment;
  /** e.g. "2 Jun 2025". */
  orderDate: string;
  amount: number;
  /** Whole-percent commission rate applied to this order, e.g. 10 for 10%. */
  commissionRate: number;
  /** Commission deducted from `amount` (rendered with a leading "−"). */
  commissionAmount: number;
  netToVendor: number;
}

export interface Payout {
  /** Lowercase slug used for the `/payments/[id]` detail route, e.g. "pay-7801". */
  id: string;
  /** Display payout number, e.g. "PAY-7801". */
  payoutNumber: string;
  vendorName: string;
  /** Kebab-case slug — matches `Vendor.slug` in `vendors.ts` for the vendors that overlap so a
   * "View Vendor" link could work; generated the same way for the rest. */
  vendorSlug: string;
  vendorType: VendorType;
  /** Settlement cycle covered by this payout, e.g. "1–15 Jun 2025". */
  periodLabel: string;
  ordersCount: number;
  grossAmount: number;
  /** Platform commission deducted from the gross amount (rendered with a leading "−"). */
  commission: number;
  netAmount: number;
  /** Display due/release date, e.g. "20 Jun 2025". */
  dueDate: string;
  status: PayoutStatus;

  /** Fields below are only surfaced on the Payout Detail screen. */

  /** Sample of orders included in this payout cycle — see `PayoutOrderLine` for why this isn't
   * necessarily `ordersCount` long. */
  orders: PayoutOrderLine[];
  /** Count of orders in this cycle dispatched after the vendor SLA window, driving `shippingPenalty`. */
  lateDispatchCount: number;
  /** Flat penalty deducted for late dispatches (rendered with a leading "−"). */
  shippingPenalty: number;
  /** Count of orders in this cycle that were returned, driving `returnDeduction`. */
  returnsCount: number;
  /** Amount clawed back for returned orders (rendered with a leading "−"). */
  returnDeduction: number;
  /** GST charged on the platform commission — a fixed 18% of `commission`, rounded. */
  gstOnCommission: number;
  /** Tax deducted at source — a fixed 1% of `grossAmount`, rounded. */
  tdsDeducted: number;
  /** `netAmount` minus every further deduction above — the amount actually released to the vendor. */
  finalNetPayout: number;

  /** Masked settlement account, e.g. "XXXX XXXX 4821" — copied from the matching `Vendor` in
   * `vendors.ts` when `vendorSlug` overlaps, otherwise a plausible standalone value. */
  bankAccountMasked: string;
  ifscCode: string;
  /** Bank display name derived from `ifscCode`'s issuer prefix, e.g. "HDFC Bank". */
  bankName: string;
  accountHolderName: string;
}

